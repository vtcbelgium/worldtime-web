export const ALLOW = Object.freeze({
  OBSERVE:'AUTO_READ',
  AUDIT:'AUTO_READ',
  DRAFT_REPORT:'AUTO_READ',
  WRITE_TESTS:'PR_REVIEW',
  OPEN_DRAFT_PR:'PR_REVIEW',
  EDIT_CONTENT:'OWNER_APPROVAL',
  ADD_CITY_PAGES:'OWNER_APPROVAL',
  DEPLOY_PRODUCTION:'OWNER_APPROVAL',
  SUBMIT_INDEXNOW:'OWNER_APPROVAL',
  REQUEST_INDEXING:'OWNER_APPROVAL',
  START_RECURRING_JOB:'OWNER_APPROVAL',
  SEND_OUTREACH:'OWNER_APPROVAL',
  BUY_BACKLINKS:'PROHIBITED',
  KEYWORD_STUFFING:'PROHIBITED',
  MASS_GENERATE_THIN_PAGES:'PROHIBITED',
  GOOGLE_GENERAL_INDEXING_API:'PROHIBITED',
  FAKE_REVIEWS:'PROHIBITED'
});
export function decisionFor(action) {
  return ALLOW[action] || 'OWNER_APPROVAL'; // fail-closed on unknown actions
}
